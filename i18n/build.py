"""Turns the line-based translation files into what the package needs:
  - contents/code/translations.js   (used by the QML side inside KWin)
  - contents/locale/<lang>/LC_MESSAGES/kdesnaplayout.mo
    (used by System Settings for the quick menu, config.ui)
Run after editing any <lang>.txt:  python3 i18n/build.py"""
import glob, json, os, struct

here = os.path.dirname(os.path.abspath(__file__))
pkg = os.path.join(here, "..", "package", "contents")
master = open(os.path.join(here, "master.txt"), encoding="utf-8").read().rstrip("\n").split("\n")
ui_strings = json.load(open(os.path.join(here, "strings.json"), encoding="utf-8"))["ui"]


def write_mo(path, pairs):
    # GNU gettext .mo, little endian, no hash table
    pairs = sorted(pairs.items())
    ids = b""; strs = b""; offs = []
    for k, v in pairs:
        kb, vb = k.encode("utf-8"), v.encode("utf-8")
        offs.append((len(ids), len(kb), len(strs), len(vb)))
        ids += kb + b"\0"; strs += vb + b"\0"
    n = len(pairs)
    key_start = 7 * 4 + 16 * n
    val_start = key_start + len(ids)
    koffs, voffs = [], []
    for o1, l1, o2, l2 in offs:
        koffs += [l1, o1 + key_start]
        voffs += [l2, o2 + val_start]
    out = struct.pack("Iiiiiii", 0x950412DE, 0, n, 7 * 4, 7 * 4 + n * 8, 0, 0)
    out += struct.pack("%di" % len(koffs), *koffs)
    out += struct.pack("%di" % len(voffs), *voffs)
    out += ids + strs
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "wb").write(out)


data = {}
for path in sorted(glob.glob(os.path.join(here, "*.txt"))):
    lang = os.path.basename(path)[:-4]
    if lang == "master":
        continue
    lines = open(path, encoding="utf-8").read().rstrip("\n").split("\n")
    if len(lines) != len(master):
        raise SystemExit("%s: %d lines, expected %d" % (lang, len(lines), len(master)))
    table = {src: tr for src, tr in zip(master, lines) if tr != src}
    data[lang] = table
    header = "Content-Type: text/plain; charset=UTF-8\nLanguage: %s\n" % lang
    mo = {"": header}
    mo.update({s: table.get(s, s) for s in ui_strings})
    write_mo(os.path.join(pkg, "locale", lang, "LC_MESSAGES", "kdesnaplayout.mo"), mo)

js = ".pragma library\n// Generated by i18n/build.py from i18n/*.txt. Edit those files, not this one.\n"
js += "var data = " + json.dumps(data, ensure_ascii=False, separators=(",", ":"), sort_keys=True) + ";\n"
open(os.path.join(pkg, "code", "translations.js"), "w", encoding="utf-8").write(js)
print("languages:", len(data), " ".join(sorted(data)))
